import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {angles,angleDiff,aligned} from './panorama-flow.js';
const close=(a,b)=>assert.ok(Math.abs(a-b)<.00001,a+' != '+b);
let p=angles(0,90,0);close(p.yaw,0);close(p.pitch,0);close(p.roll,0);
p=angles(270,90,0);close(p.yaw,90);close(p.pitch,0);close(p.roll,0);
p=angles(0,140,0);close(p.pitch,50);
p=angles(0,40,0);close(p.pitch,-50);
assert.equal(angles(null,90,0),null);
close(angleDiff(0,355),5);close(angleDiff(355,0),-5);
assert.equal(aligned({yaw:358,pitch:1,roll:2},[0,0]),true);
assert.equal(aligned({yaw:25,pitch:1,roll:2},[0,0]),false);
const html=readFileSync(new URL('./panorama.html',import.meta.url),'utf8');
const source=readFileSync(new URL('./panorama.js',import.meta.url),'utf8');
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
assert.equal(ids.length,new Set(ids).size);
for(const [,id] of source.matchAll(/\$\('([^']+)'\)/g))assert.ok(ids.includes(id),'Missing DOM id '+id);
for(const id of ['middle','upper','lower','poles','discard-point'])assert.ok(ids.includes(id));
assert.ok(!/\son\w+="/i.test(html),'Inline handlers forbidden by CSP');
console.log('Panorama sensor and DOM checks passed');
